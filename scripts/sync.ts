// One command for every file derived from the language.
//
//   bun run sync           regenerate everything that is out of date
//   bun run sync --check   report what is out of date and exit 1, writing nothing
//                          (the slow steps, web apps and JetBrains, still rebuild in
//                          a scratch copy so they can be compared)
//   bun run check          sync --check, then the whole test suite
//
// The single sources: src/core (builtins.ts, docs.ts, lexer.ts KEYWORDS, pitch.ts
// SCALES and DRUMS, interp.ts INSTRUMENTS, synth.ts INSTRUMENT_DOCS) for words and
// docs, and package.json for the version. Everything below is derived from them.
// To add a derived file, add a step here and a freshness test in tests/sync.test.ts.
import { readFileSync, writeFileSync, existsSync, mkdtempSync, cpSync, rmSync, statSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { referenceMarkdown } from "./gen-reference";
import { textmateGrammar } from "./grammar";
import { vimSyntax, emacsMode } from "./gen-editors";

export const root = join(import.meta.dir, "..");
const read = (p: string) => (existsSync(join(root, p)) ? readFileSync(join(root, p), "utf8") : "");

export const version = (): string => JSON.parse(read("package.json")).version;

// The version, stamped wherever a copy has to exist.
function stampVersion(path: string, text: string): string {
  const v = version();
  switch (path) {
    case "src/core/version.ts":
      return `// Generated by scripts/sync.ts from package.json. Do not edit; run \`bun run sync\`.\nexport const VERSION = "${v}";\n`;
    case "editors/vscode/package.json": {
      const j = JSON.parse(text); j.version = v; return JSON.stringify(j, null, 2) + "\n";
    }
    case "editors/vscode/package-lock.json": {
      const j = JSON.parse(text); j.version = v; if (j.packages?.[""]) j.packages[""].version = v; return JSON.stringify(j, null, 2) + "\n";
    }
    case "package.json":
      return text.replace(/(-o tine-)[\d.]+(\.vsix)/, `$1${v}$2`);
  }
  throw new Error(path);
}

// Fast steps: pure functions of the sources, compared in memory.
export function derivedFiles(): Record<string, string> {
  const grammar = textmateGrammar();
  const out: Record<string, string> = {
    "docs/REFERENCE.md": referenceMarkdown(),
    "editors/textmate/tine.tmLanguage.json": grammar,
    "editors/vscode/syntaxes/tine.tmLanguage.json": grammar,
    "editors/vim/syntax/tine.vim": vimSyntax(),
    "editors/emacs/tine-mode.el": emacsMode(read("editors/emacs/tine-mode.el")),
  };
  for (const p of ["src/core/version.ts", "editors/vscode/package.json", "editors/vscode/package-lock.json", "package.json"])
    out[p] = stampVersion(p, read(p));
  return out;
}

// Slow steps: scripts that write files themselves. Each lists the files it owns.
const SLOW: { name: string; script: string; owns: string[] }[] = [
  { name: "web apps", script: "scripts/build-web.ts", owns: ["src/cli/assets.gen.ts"] },
  { name: "JetBrains", script: "scripts/gen-jetbrains.ts", owns: [
    // only what gen-jetbrains.ts writes; README.md and the plugin source are hand-written
    "editors/jetbrains/templates", "editors/jetbrains/tine-settings.zip", "editors/jetbrains/tine-bundle",
    "editors/jetbrains/lsp4ij", "editors/jetbrains/plugin/src/main/resources/liveTemplates", "editors/jetbrains/plugin/src/main/resources/tine",
  ] },
];

function snapshot(dir: string, paths: string[]): Map<string, string> {
  const m = new Map<string, string>();
  const walk = (rel: string) => {
    const abs = join(dir, rel);
    if (!existsSync(abs)) return;
    if (!statSync(abs).isDirectory()) { m.set(rel, Bun.hash(readFileSync(abs)).toString()); return; }
    for (const e of new Bun.Glob("**/*").scanSync({ cwd: abs, onlyFiles: true, dot: true })) m.set(join(rel, e), Bun.hash(readFileSync(join(abs, e))).toString());
  };
  for (const p of paths) walk(p);
  return m;
}
const changed = (a: Map<string, string>, b: Map<string, string>) =>
  [...new Set([...a.keys(), ...b.keys()])].filter(k => a.get(k) !== b.get(k)).sort();

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const fast = process.argv.includes("--fast");
  const stale: string[] = [];

  for (const [p, want] of Object.entries(derivedFiles())) {
    if (read(p) === want) continue;
    stale.push(p);
    if (!check) writeFileSync(join(root, p), want);
  }

  if (!fast) {
    // In check mode the slow steps run in a scratch copy, so the tree is untouched.
    let dir = root;
    if (check) {
      dir = mkdtempSync(join(tmpdir(), "tine-sync-"));
      cpSync(root, dir, { recursive: true, filter: s => !/^\/(dist|\.git|node_modules)(\/|$)/.test(s.slice(root.length)) });
      if (existsSync(join(root, "node_modules"))) symlinkSync(join(root, "node_modules"), join(dir, "node_modules"));
    }
    for (const step of SLOW) {
      if (!existsSync(join(dir, step.script))) { console.log(`skip ${step.name}: ${step.script} not present`); continue; }
      const before = snapshot(dir, step.owns);
      const r = spawnSync("bun", [step.script], { cwd: dir, stdio: ["ignore", "ignore", "inherit"] });
      if (r.status !== 0) { console.error(`${step.name}: ${step.script} failed`); process.exit(2); }
      stale.push(...changed(before, snapshot(dir, step.owns)));
    }
    if (check) rmSync(dir, { recursive: true, force: true });
  }

  if (!stale.length) console.log("sync: every derived file is current");
  else if (check) { console.log(`sync --check: ${stale.length} derived file(s) out of date:\n  ${stale.join("\n  ")}\nrun \`bun run sync\` and commit the result`); process.exit(1); }
  else console.log(`sync: regenerated ${stale.length} file(s):\n  ${stale.join("\n  ")}`);
}
