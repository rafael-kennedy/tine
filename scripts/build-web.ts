// Bundle the browser apps into single self-contained HTML files, and
// generate src/cli/assets.gen.ts so the tine binary can serve them offline.
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
mkdirSync(dist, { recursive: true });

const FONTS = `<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,500;9..144,600&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;600&display=swap" rel="stylesheet">`;
const FAVICON = `<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 64 64'><rect width='64' height='64' rx='14' fill='#14161c'/><g fill='none' stroke-linecap='round'><path d='M23 10v18a9 9 0 0 0 18 0V10' stroke='#d4a944' stroke-width='6'/><path d='M32 37v18' stroke='#d4a944' stroke-width='6'/></g></svg>`)}">`;

const apps = [
  { name: "daw", entry: "src/web/daw.ts", title: "Tine DAW", desc: "Live-coding workstation for the Tine music language." },
  { name: "learn", entry: "src/web/learn.ts", title: "Learn Tine", desc: "An interactive tutorial for the Tine music language." },
  { name: "player", entry: "src/web/player.ts", title: "Tine Player", desc: "A piece made with Tine." },
];

// The synthesis worker travels inside each page as text and starts from a Blob URL.
const wres = await Bun.build({ entrypoints: [join(root, "src/web/synth-worker.ts")], target: "browser", minify: true, format: "esm" });
if (!wres.success) { for (const l of wres.logs) console.error(l); process.exit(1); }
const WORKER = `<script type="text/js-worker" id="tine-synth-worker">${(await wres.outputs[0].text()).replace(/<\/script/gi, "<\\/script")}</script>`;

const out: Record<string, string> = {};
for (const app of apps) {
  if (!existsSync(join(root, app.entry))) { console.log(`skip ${app.name}`); continue; }
  const res = await Bun.build({ entrypoints: [join(root, app.entry)], target: "browser", minify: true, format: "esm" });
  if (!res.success) { for (const l of res.logs) console.error(l); process.exit(1); }
  const js = (await res.outputs[0].text()).replace(/<\/script/gi, "<\\/script");
  const extra = app.name === "player" ? `<script type="text/tine" id="piece"></script>` : "";
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${app.title}</title><meta name="description" content="${app.desc}">${FAVICON}${FONTS}</head><body>${extra}${WORKER}<script type="module">${js}</script></body></html>`;
  writeFileSync(join(dist, `${app.name}.html`), html);
  out[app.name] = html;
  console.log(`dist/${app.name}.html  ${(html.length / 1024).toFixed(0)} KB`);
}

writeFileSync(join(root, "src/cli/assets.gen.ts"),
  `// generated by scripts/build-web.ts; do not edit\n` +
  `export const DAW_HTML = ${JSON.stringify(out.daw ?? "")};\n` +
  `export const LEARN_HTML = ${JSON.stringify(out.learn ?? "")};\n` +
  `export const PLAYER_HTML = ${JSON.stringify(out.player ?? "")};\n`);
