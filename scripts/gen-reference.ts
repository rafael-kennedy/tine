import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { builtinList, SCALES, DRUMS, CHORDS, INSTRUMENT_DOCS, parseQuality } from "../src/core";
import { GUIDES } from "../src/core/guide";

const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const anchor = (name: string) => name.toLowerCase();
function byCategory() {
  const m = new Map<string, ReturnType<typeof builtinList>>();
  for (const b of builtinList()) { if (!m.has(b.category)) m.set(b.category, []); m.get(b.category)!.push(b); }
  return m;
}
export function referenceMarkdown(): string {
const head = readFileSync(join(import.meta.dir, "../docs/reference-head.md"), "utf8");
let out = head + "\n## Built-in functions\n\nAny function can be called as `f(x, y)` or, on its first argument, as `x.f(y)`. With no other arguments the parentheses are optional: `p.rev`. Each function links to its examples in [FUNCTIONS.md](FUNCTIONS.md).\n";
for (const [cat, bs] of byCategory()) {
  out += `\n### ${cap(cat)}\n\n| Function | Description |\n| --- | --- |\n`;
  for (const b of bs) out += `| [\`${b.sig.replace(/\|/g, "\\|")}\`](FUNCTIONS.md#${anchor(b.name)}) | ${b.doc.replace(/\|/g, "\\|")} |\n`;
}
out += `\n## Scales\n\n| Name | Steps (semitones) |\n| --- | --- |\n`;
for (const [k, s] of Object.entries(SCALES)) out += `| \`${k}\` | ${s.steps.map(x => Math.round(x * 100) / 100).join(" ")}${Math.abs(s.period - 12) > 1e-9 ? ` (period ${Math.round(s.period * 100) / 100})` : ""} |\n`;
out += `\n## Chord qualities\n\nAfter \`@\` you write a chord symbol the way a lead sheet does: \`c@maj7\`, \`g@7b9\`, \`f#@m7b5\`, \`bb@13#11\`, \`d@9sus4\`, \`eb@7alt\`, and a slash bass with \`c@7/e\`. On a degree, plain numbers count diatonic chord tones (\`^5@7\` is the seventh chord on the fifth degree, \`^2@3\` a triad), symbols give a fixed quality (\`^2@m7\`), and on an altered degree a number names the quality (\`^b7@7\` is a dominant seventh). \`changes("Dm7 G7 | Cmaj7")\` reads whole lead sheets with the same symbols.\n\n`;
out += `Symbols are parsed, not looked up, so they combine freely. The grammar: a family (\`m\`, \`maj\`/\`M\`, \`dim\`/\`o\`, \`aug\`/\`+\`, \`m7b5\`, \`mmaj\`), then a number (\`5 6 69 7 9 11 13\`; 9, 11 and 13 include the seventh and the extensions below them, except 13 skips the 11 on major and dominant chords), then any of \`sus2 sus4 sus\`, \`b5 #5 b9 #9 #11 b13\`, \`add2 add4 add9 add11 add13\`, \`no3 no5\`, \`alt\` (b9, #9 and b13 with no fifth). Some examples:\n\n| Symbol | Semitones |\n| --- | --- |\n`;
for (const k of ["", "m", "7", "maj7", "m7", "m7b5", "dim7", "mmaj7", "6", "69", "9", "maj9", "m9", "11", "m11", "13", "m13", "7sus4", "9sus4", "7b9", "7#9", "7#11", "7b13", "7alt", "maj7#11", "aug", "7#5"]) out += `| \`${k || "(none: major)"}\` | ${parseQuality(k)!.join(" ")} |\n`;
out += `\nAlso available by name: ${Object.keys(CHORDS).map(k => "\`" + k + "\`").join(", ")} (including \`otonal\` and \`utonal\` for just intonation).\n`;
out += `\n## Drums\n\n| Name | General MIDI note |\n| --- | --- |\n`;
for (const [k, v] of Object.entries(DRUMS)) out += `| \`${k}\` | ${v} |\n`;
out += `\n## Instruments\n\n| Name | Sound |\n| --- | --- |\n`;
for (const [k, v] of Object.entries(INSTRUMENT_DOCS)) out += `| \`${k}\` | ${v} |\n`;
return out;
}

// Every builtin with its guide: an introduction and examples, from src/core/guide.
export function functionsMarkdown(): string {
  // `name` in the text links to that function, except to the one being read
  let self = "";
  const link = (text: string) => text.replace(/`([^`]+)`/g, (m, c: string) => {
    const name = c.match(/^\.?([A-Za-z_][A-Za-z0-9_]*)(?:\(|$)/)?.[1];
    return name && name !== self && GUIDES[name] ? `[${m}](#${anchor(name)})` : m;
  });
  let out = "# Tine functions, with examples\n\nEvery built-in function, with a few examples of different ways to use it. Each example is a complete piece: paste it into the DAW or a file and it plays. The same guide is in the DAW's Help tab, where the examples play in place. The short form of each function is in [REFERENCE.md](REFERENCE.md).\n\n<!-- Generated by scripts/sync.ts from src/core/guide. Do not edit; run `bun run sync`. -->\n";
  const cats = byCategory();
  out += "\n";
  for (const [cat, bs] of cats) out += `- **${cap(cat)}**: ${bs.map(b => `[${b.name}](#${anchor(b.name)})`).join(", ")}\n`;
  for (const [cat, bs] of cats) {
    out += `\n## ${cap(cat)}\n`;
    for (const b of bs) {
      const g = GUIDES[b.name];
      self = b.name;
      out += `\n### ${b.name}\n\n\`${b.sig}\`: ${b.doc}\n`;
      if (!g) continue;
      out += `\n${link(g.intro)}\n`;
      for (const e of g.examples) {
        // a block that needs a device is fenced "tine device", so tests/sync.test.ts does not expect it to play
        out += `\n${link(e.say)}${e.live === false ? " *(Needs a file, a device or the network to be heard.)*" : ""}\n\n\`\`\`tine${e.live === false ? " device" : ""}\n${e.code}\n\`\`\`\n`;
      }
      if (g.see?.length) out += `\nSee also: ${g.see.map(s => `[${s}](#${anchor(s)})`).join(", ")}.\n`;
    }
  }
  return out;
}

if (import.meta.main) {
  writeFileSync(join(import.meta.dir, "../docs/REFERENCE.md"), referenceMarkdown());
  writeFileSync(join(import.meta.dir, "../docs/FUNCTIONS.md"), functionsMarkdown());
  console.log("docs/REFERENCE.md and docs/FUNCTIONS.md written");
}
