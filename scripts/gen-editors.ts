// Word lists for the editor modes that cannot read the TextMate grammar (Vim,
// Neovim through the Vim runtime, Emacs). Generated from the same sources as
// the grammar and the language server, so a new builtin, scale, drum or
// instrument reaches them by running `bun run sync`.
import { SCALES, DRUMS, INSTRUMENTS } from "../src/core";
import { DECLARATIONS, CONTROL, BOOLEANS, DIRECTIVES } from "./grammar";

const drums = () => Object.keys(DRUMS);
const types = () => [...Object.keys(SCALES), ...INSTRUMENTS];
// Vim's :syn keyword lines get unwieldy past a few hundred characters.
const wrap = (prefix: string, words: string[]) => {
  const lines: string[] = []; let cur: string[] = [];
  for (const w of words) { cur.push(w); if (cur.join(" ").length > 100) { lines.push(`${prefix} ${cur.join(" ")}`); cur = []; } }
  if (cur.length) lines.push(`${prefix} ${cur.join(" ")}`);
  return lines.join("\n");
};

export function vimSyntax(): string {
  return `" Vim syntax file for Tine, a programming language for music
" Generated by scripts/sync.ts from the Tine core. Do not edit; run \`bun run sync\`.
if exists("b:current_syntax") | finish | endif
syn match   tineComment  "--.*$"
syn region  tineString   start=+"+ skip=+\\\\"+ end=+"+
syn keyword tineKeyword  ${[...DECLARATIONS, "form", ...CONTROL, "use"].join(" ")}
syn match tineKeyword "^\\s*\\zsactive\\ze\\s\\+voice\\>"
syn match tineToggle "--\\s*@\\w\\+\\s*$"
hi def link tineToggle Label
syn keyword tineDirective ${DIRECTIVES.filter(d => d !== "form" && d !== "use").join(" ")}
syn keyword tineBool     ${[...BOOLEANS, "silence"].join(" ")}
syn match   tineDegree   "\\^\\%(#\\|b\\)*-\\?\\d\\+"
syn match   tineNote     "\\<[A-Ga-g]\\%(#\\|b\\)*\\d\\?\\>"
syn match   tineNumber   "\\<\\d\\+\\%(\\.\\d\\+\\)\\?\\%(hz\\|c\\>\\|\\\\\\d\\+\\)\\?"
syn match   tineChord    "@[A-Za-z0-9]\\+"
syn match   tinePhraseOp "[|?!_]"
syn match   tineBracket  "[\\[\\]{}<>]"
${wrap("syn keyword tineDrum    ", drums())}
${wrap("syn keyword tineType    ", types())}
syn match   tineFunction "\\<[a-z_][A-Za-z0-9_]*\\ze("
syn match   tineMethod   "\\.\\zs[a-z_][A-Za-z0-9_]*"
hi def link tineComment Comment
hi def link tineString String
hi def link tineKeyword Keyword
hi def link tineDirective PreProc
hi def link tineBool Boolean
hi def link tineDegree Constant
hi def link tineNote Constant
hi def link tineNumber Number
hi def link tineChord Operator
hi def link tinePhraseOp Special
hi def link tineBracket Delimiter
hi def link tineDrum Identifier
hi def link tineType Type
hi def link tineFunction Function
hi def link tineMethod Function
let b:current_syntax = "tine"
`;
}

const BEGIN = ";; BEGIN GENERATED by scripts/sync.ts: do not edit, run `bun run sync`";
const END = ";; END GENERATED";
const elist = (xs: string[]) => xs.map(x => `"${x}"`).join(" ");

// Replaces the generated region of tine-mode.el; everything else in the file is hand-written.
export function emacsMode(current: string): string {
  const region = `${BEGIN}
(defvar tine-font-lock-keywords
  \`(("--.*$" . font-lock-comment-face)
    (,(regexp-opt '(${elist([...DECLARATIONS, "form", ...CONTROL, "use"])}) 'words) . font-lock-keyword-face)
    (,(regexp-opt '(${elist(DIRECTIVES.filter(d => d !== "form" && d !== "use"))}) 'words) . font-lock-preprocessor-face)
    (,(regexp-opt '(${elist([...BOOLEANS, "silence"])}) 'words) . font-lock-constant-face)
    ("\\\\^\\\\(#\\\\|b\\\\)*-?[0-9]+" . font-lock-constant-face)
    ("\\\\_<[A-Ga-g]\\\\(#\\\\|b\\\\)*[0-9]?\\\\_>" . font-lock-constant-face)
    ("@[A-Za-z0-9]+" . font-lock-builtin-face)
    (,(regexp-opt '(${elist(drums())}) 'symbols) . font-lock-variable-name-face)
    (,(regexp-opt '(${elist(types())}) 'symbols) . font-lock-type-face)
    ("\\\\_<\\\\([a-z_][A-Za-z0-9_]*\\\\)(" 1 font-lock-function-name-face)
    ("\\\\.\\\\([a-z_][A-Za-z0-9_]*\\\\)" 1 font-lock-function-name-face)))
${END}`;
  const a = current.indexOf(BEGIN), b = current.indexOf(END);
  if (a >= 0 && b > a) return current.slice(0, a) + region + current.slice(b + END.length);
  // first run: replace the hand-written defvar
  const start = current.indexOf("(defvar tine-font-lock-keywords");
  const stop = current.indexOf("(defvar tine-mode-syntax-table");
  if (start < 0 || stop < 0) throw new Error("tine-mode.el: cannot find tine-font-lock-keywords");
  return current.slice(0, start) + region + "\n\n" + current.slice(stop);
}
